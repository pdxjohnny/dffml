def get_argument_datatype(func: Callable, name: str) -> Type:
    """
    >>> def feedface(a: str):
    ...     pass
    >>> get_argument_datatype(feedface, "a")
    <class 'str'>
    """
    return inspect.signature(func).parameters()[name].param_annotation


